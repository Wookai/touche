// Generates engine/src/layout.generated.ts from data/schema/layout.schema.json, the
// one schema source (DESIGN.md, Stack and architecture). `npm run types` writes it;
// engine/test/types.test.ts fails when the committed file is stale.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { compile, type JSONSchema } from "json-schema-to-typescript";

const SCHEMA = new URL("../../data/schema/layout.schema.json", import.meta.url);
const OUTPUT = fileURLToPath(new URL("../src/layout.generated.ts", import.meta.url));
const BIOME = fileURLToPath(new URL("../../node_modules/.bin/biome", import.meta.url));

async function generate(): Promise<string> {
  const schema = JSON.parse(readFileSync(SCHEMA, "utf8")) as JSONSchema;
  const ts = await compile(schema, "Layout", {
    bannerComment:
      "// Generated by `npm run types` from data/schema/layout.schema.json. Do not edit.",
    format: false,
  });
  // Formatted by the repo's Biome so the committed file passes `npm run lint` unchanged.
  return execFileSync(BIOME, ["format", `--stdin-file-path=${OUTPUT}`], {
    input: ts,
    encoding: "utf8",
  });
}

if (import.meta.main) {
  writeFileSync(OUTPUT, await generate());
}

export async function isStale(): Promise<boolean> {
  return readFileSync(OUTPUT, "utf8") !== (await generate());
}
